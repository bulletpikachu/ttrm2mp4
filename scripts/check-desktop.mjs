import assert from 'node:assert/strict';
import {mkdir,mkdtemp,readFile,stat,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {_electron} from 'playwright-core';
import electron from 'electron';
const root=fileURLToPath(new URL('../',import.meta.url));
const temp=await mkdtemp(path.join(tmpdir(),'replay-desktop-check-'));
const userData=path.join(temp,'preferences');
const fixture=path.join(temp,'replay.ttrm');
const replay=JSON.parse(await readFile(path.join(root,'replay.ttrm'),'utf8'));
replay.replay.rounds=replay.replay.rounds.slice(0,1);
await writeFile(fixture,JSON.stringify(replay));
await mkdir(userData);
await writeFile(path.join(userData,'preferences.json'),JSON.stringify({duration:2}));
const packaged=process.argv[2];
const executable=packaged||electron;
let app;
try{
  app=await _electron.launch({executablePath:executable,args:packaged?[]:[root],cwd:temp,env:{...process.env,REPLAY_DESKTOP_USER_DATA:userData}});
  console.log('CHECK: app launched');
  const page=await app.firstWindow();
  page.on('console',message=>console.log('UI:',message.text()));
  app.process().stderr.on('data',data=>console.log('APP:',String(data).slice(0,2000)));
  console.log('CHECK: window ready',page.url());page.setDefaultTimeout(120000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  console.log('CHECK: heading');
  await page.getByRole('heading',{name:'ttrm2mp4',exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>typeof window.require),'undefined','UI has no Node access');
  await page.evaluate(()=>{window.testEvents=[];window.replayRender.onEvent(event=>window.testEvents.push(event));});
  await page.locator('input[type=file]').evaluate(input=>input.addEventListener('change',()=>{window.dropFiles=Array.from(input.files)},{capture:true}));
  console.log('CHECK: adding replay');
  const chooserReady=page.waitForEvent('filechooser');
  await page.getByRole('button',{name:'Choose replay files',exact:true}).click();
  const chooser=await chooserReady;await chooser.setFiles(fixture);
  const queueButton=page.getByRole('button',{name:/^Queue /});
  await page.getByRole('button',{name:'Queue 1',exact:true}).waitFor();
  const openingQueue=app.waitForEvent('window');
  await queueButton.click();
  const queue=await openingQueue;
  queue.setDefaultTimeout(15000);
  queue.on('pageerror',error=>errors.push(error.message));
  await queue.getByRole('region',{name:'Replay queue',exact:true}).waitFor();
  await queue.getByText('replay.ttrm',{exact:true}).waitFor();
  await queue.getByRole('button',{name:'Clear queue',exact:true}).click();
  await page.getByRole('button',{name:'Queue 0',exact:true}).waitFor();
  await page.evaluate(()=>{const transfer=new DataTransfer();transfer.items.add(window.dropFiles[0]);document.querySelector('.dropzone').dispatchEvent(new DragEvent('drop',{bubbles:true,cancelable:true,dataTransfer:transfer}));});
  await queue.getByText('replay.ttrm',{exact:true}).waitFor();
  await page.getByRole('region',{name:'Render logs',exact:true}).waitFor();
  assert.equal(await page.getByRole('spinbutton',{name:'Preview length'}).count(),0);
  await app.evaluate(({dialog},directory)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[directory]});},temp);
  await page.getByRole('button',{name:'Choose output folder',exact:true}).click();
  await page.waitForFunction(expected=>document.querySelector('input[aria-label="Output folder"]').value===expected,temp);
  await app.evaluate(({dialog},directory)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[directory]});},path.join(root,'client'));
  await page.getByRole('button',{name:'Choose game files folder',exact:true}).click();
  await page.waitForFunction(expected=>document.querySelector('input[aria-label="Game files folder"]').value===expected,path.join(root,'client'));
  if(process.argv[3])await page.getByRole('combobox',{name:'Rendering backend'}).selectOption(process.argv[3]);
  console.log('CHECK: start export');
  await page.getByRole('button',{name:'Render',exact:true}).click();
  console.log('CHECK: export clicked');
  await Promise.race([page.getByText('All exports complete',{exact:true}).waitFor({timeout:180000}),page.getByRole('alert').waitFor().then(async()=>{throw Error(await page.getByRole('alert').innerText())})]);
  assert.match(await page.locator('.logs pre').innerText(),/Saved /,'Export messages appear in the log column');
  await queue.getByRole('button',{name:'Show video for replay.ttrm'}).waitFor();
  const events=await page.evaluate(()=>window.testEvents);
  assert(events.some(event=>event.type==='backend'),'Structured backend selection arrives');
  assert(events.some(event=>event.type==='progress'),'Structured rendering progress arrives');
  const result=events.find(event=>event.type==='finished');assert(result?.output);
  assert((await stat(result.output)).size>0,'GUI produced a video');
  const report=JSON.parse(await readFile(result.output.replace(/\.mp4$/,'.json'),'utf8'));
  assert(report.count>120,'Old preview length must not truncate the export');
  assert.equal(report.networkingDisabled,true);
  assert.equal(report.rounds.length,1);
  assert(!report.rounds[0].partial,'The replay finishes its round');
  if(process.argv[3]==='portable')assert(!report.pipeline.startsWith('native-'));
  else if(process.platform==='darwin'&&process.arch==='arm64')assert.equal(report.pipeline,'native-angle-iosurface-x264');
  const prefs=JSON.parse(await readFile(path.join(temp,'preferences/preferences.json'),'utf8'));
  assert(!Object.hasOwn(prefs,'duration'));assert.equal(prefs.backend,process.argv[3]||'auto');
  await page.screenshot({path:'/tmp/replay-render-desktop.png',fullPage:true});
  await queue.screenshot({path:'/tmp/ttrm2mp4-queue.png'});
  // Remove/re-add, then cancel during startup. Cancel must not trigger fallback.
  await queue.getByRole('button',{name:'Remove replay.ttrm'}).click();
  await page.getByRole('button',{name:'Queue 0',exact:true}).waitFor();
  await page.locator('input[type=file]').setInputFiles(path.join(root,'replay.ttrm'));
  await queue.getByText('replay.ttrm',{exact:true}).waitFor();
  await page.evaluate(()=>{window.testEvents=[];});
  await page.getByRole('button',{name:'Render',exact:true}).click();
  await page.waitForFunction(()=>window.testEvents.some(event=>event.type==='progress'));
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.getByText('Export cancelled',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Render',exact:true}).waitFor();
  const cancelled=await page.evaluate(()=>window.testEvents);
  const pid=cancelled.find(event=>event.type==='worker-started').pid;
  assert.throws(()=>process.kill(pid,0),error=>error.code==='ESRCH','Owned rendering worker exited after cancellation');
  assert(!cancelled.some(event=>event.type==='finished'),'Cancellation never becomes completion');
  assert.equal(errors.length,0,errors.join('\n'));
  console.log(JSON.stringify({passed:true,packaged:!!packaged,output:result.output,report:result.output.replace(/\.mp4$/,'.json'),screenshot:'/tmp/replay-render-desktop.png',temp}));
}finally{if(app){const timer=setTimeout(()=>app.process().kill('SIGKILL'),5000);try{await app.close()}finally{clearTimeout(timer)}}}
