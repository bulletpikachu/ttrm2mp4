import {readFile,writeFile} from 'node:fs/promises';
import {spawn} from 'node:child_process';
import assert from 'node:assert/strict';
import path from 'node:path';
import ffmpeg from 'ffmpeg-static';
const [input,reference,output,gate='40']=process.argv.slice(2);
if(!input||!reference||!output)throw Error('Usage: node scripts/verify-window-cuts.mjs candidate.json reference.mp4 audit.json [minimumPSNR]');
const report=JSON.parse(await readFile(input,'utf8')),minimum=Number(gate);
assert(report.frameRanges===true&&Number.isFinite(minimum));
const cuts=report.workers.map(w=>w.frameWindow.startFrame).filter(n=>n>0&&n<report.count),frames=[...new Set(cuts.flatMap(n=>[n-2,n-1,n,n+1,n+2]).filter(n=>n>=0&&n<report.count))].sort((a,b)=>a-b);
assert(frames.length>0,'Export needs an internal frame-window cut');
const selection=frames.map(n=>`eq(n\\,${n})`).join('+'),select=`select=${selection},setpts=N/(${report.fps}*TB),format=yuv420p`;
const filter=`[0:v]${select}[candidate];[1:v]${select}[reference];[candidate][reference]psnr=stats_file=-:shortest=1`;
const child=spawn(ffmpeg,['-hide_banner','-loglevel','warning','-nostdin','-i',report.output,'-i',reference,'-filter_complex',filter,'-an','-f','null','-'],{windowsHide:true,stdio:['ignore','pipe','pipe']});
let logs='',errors='';child.stdout.on('data',b=>{logs+=b});child.stderr.on('data',b=>{errors=(errors+b).slice(-4000)});
await new Promise((resolve,reject)=>{child.once('error',reject);child.once('close',code=>code===0?resolve():reject(Error(errors)))});
const values=logs.split('\n').filter(line=>line.startsWith('n:')).map(line=>Object.fromEntries(line.trim().split(/\s+/).map(field=>field.split(':'))));
assert.equal(values.length,frames.length,'Every neighboring cut frame was compared');
const scores=values.map((value,i)=>({frame:frames[i],psnr:value.psnr_avg==='inf'?Infinity:Number(value.psnr_avg)})),minimumPSNR=Math.min(...scores.map(v=>v.psnr));
assert(!Number.isNaN(minimumPSNR));
const result={report:path.resolve(input),reference:path.resolve(reference),cuts,samples:scores,minimumPSNR,minimumRequiredPSNR:minimum,passed:minimumPSNR>=minimum};
await writeFile(output,JSON.stringify(result,null,2)+'\n');
console.log(`${frames.length} decoded cut/neighbor frames compared with continuous native reference; minimum PSNR ${minimumPSNR} dB.`);
assert(result.passed,'Frame-window cut fidelity is below the required threshold');
