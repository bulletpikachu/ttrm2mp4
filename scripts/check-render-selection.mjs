import assert from 'node:assert/strict';
import {resourceDefaults,extractOptions,positiveInteger,selectBackend,probeWorkerCount,windowsFastEnvironment} from '../src/offline/render-policy.mjs';
const env=windowsFastEnvironment({REPLAY_WINDOWS_COMPUTE:'1',REPLAY_WINDOWS_GPU_BATCH:'16',NODE_WEBGL_BACKEND:'vulkan',REPLAY_WINDOWS_NVIDIA_ADAPTER:'0',Path:'test-path'});
assert.equal(env.REPLAY_WINDOWS_COMPUTE,'0');assert.equal(env.REPLAY_WINDOWS_GPU_BATCH,'4');assert.equal(env.Path,'test-path');
assert.equal(env.NODE_WEBGL_BACKEND,'d3d11');assert.equal(env.REPLAY_WINDOWS_NVIDIA_ADAPTER,'1');
const gib=1024**3;
assert.deepEqual(resourceDefaults({cores:1,memoryBytes:2*gib}),{jobs:1,nativeThreads:1,portableThreads:1});
assert.equal(resourceDefaults({cores:6,memoryBytes:16*gib}).jobs,3);
assert.equal(resourceDefaults({cores:64,memoryBytes:4*gib}).jobs,1);
assert.equal(resourceDefaults({cores:64,memoryBytes:64*gib}).jobs,3);
assert.equal(resourceDefaults({cores:64,memoryBytes:64*gib}).nativeThreads,16);
assert.equal(resourceDefaults({cores:12,memoryBytes:10*gib},3840,2160).jobs,1);
assert.equal(resourceDefaults({cores:12,memoryBytes:24*gib}).nativeThreads,10);
assert.deepEqual(extractOptions(['a b.ttrm','--threads=4','--width','1280','--backend','portable','--jobs','2'],['backend','threads','jobs']),{values:{threads:'4',backend:'portable',jobs:'2'},args:['a b.ttrm','--width','1280']});
for(const value of ['0','-1','NaN','1.5','257'])assert.throws(()=>positiveInteger(value,'threads',256));
assert.throws(()=>extractOptions(['--threads'],['threads']));
assert.throws(()=>extractOptions(['--jobs','2','--jobs','3'],['jobs']));
let probes=0;
const base={requested:'auto',platform:'win32',arch:'x64',args:['match.ttrm','movie.mp4'],probe:async()=>{probes++}};
assert.equal((await selectBackend(base)).backend,'windows-nvidia');
assert.equal((await selectBackend({...base,platform:'darwin',arch:'arm64'})).backend,'mac');
assert.equal(probes,2);
assert.equal((await selectBackend({...base,probe:async()=>{throw Error('NVENC session unavailable')}})).backend,'portable');
assert.equal((await selectBackend({...base,args:['match.ttrm','--duration','2']})).backend,'portable');
assert.equal((await selectBackend({...base,args:['match.ttrm','--encoder','ffmpeg']})).backend,'portable');
assert.equal((await selectBackend({...base,platform:'darwin',arch:'x64'})).backend,'portable');
assert.equal((await selectBackend({...base,arch:'arm64'})).backend,'portable');
assert.equal((await selectBackend({...base,platform:'linux'})).backend,'portable');
assert.equal((await selectBackend({...base,requested:'portable'})).backend,'portable');
assert.equal((await selectBackend({...base,threadsRequested:true})).backend,'portable');
await assert.rejects(selectBackend({...base,requested:'windows-nvidia',threadsRequested:true}),/uses --jobs/);
assert.equal(resourceDefaults({cores:12,memoryBytes:512*1024**2}).nativeThreads,4);
assert.equal(probes,2,'Unsupported/explicit-portable paths never initialize native hardware');
const imported={...base,args:[...base.args,'--appearance','imported appearance.json']};
assert.equal((await selectBackend(imported)).backend,'windows-nvidia');
assert.equal((await selectBackend({...imported,platform:'darwin',arch:'arm64'})).backend,'mac');
await assert.rejects(selectBackend({...base,requested:'windows-nvidia',probe:async()=>{throw Error('Driver missing')}}),/Driver missing/);
await assert.rejects(selectBackend({...base,requested:'mac'}),/unavailable/);
await assert.rejects(selectBackend({...base,probe:async()=>{const error=Error('Cancelled');error.cancelled=true;throw error;}}),/Cancelled/);
const tries=[];
assert.equal(await probeWorkerCount({jobs:3,probe:async(i,count)=>{tries.push(count);if(count>2)throw Error('Session limit')}}),2);
assert.deepEqual(tries,[3,3,3,2,2]);
const groups=[];
assert.equal(await probeWorkerCount({jobs:3,probeGroup:async count=>{groups.push(count);if(count>1)throw Error('Session limit')}}),1);
assert.deepEqual(groups,[3,2,1]);
await assert.rejects(probeWorkerCount({jobs:3,explicit:true,probe:async()=>{throw Error('Session limit')}}),/Session limit/);
await assert.rejects(probeWorkerCount({jobs:1,probe:async()=>{throw Error('Unavailable')}}),/Unavailable/);
await assert.rejects(probeWorkerCount({jobs:3,probe:async()=>{const error=Error('Cancelled');error.cancelled=true;throw error;}}),/Cancelled/);
console.log('PASS: backend selection, native startup fallback, cancellation, explicit overrides, CPU/memory limits and option forwarding.');
