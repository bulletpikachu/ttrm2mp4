import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import ffmpeg from 'ffmpeg-static';
import { createCanvas, getDisplayInfo } from '../.native-deps/node-webgl-windows/dist/index.js';
const require = createRequire(import.meta.url);
const probe = require('../.native-deps/windows-gpu/windows-probe.node');
const canvas = createCanvas(256, 256), gl = canvas.getContext('webgl2');
assert(gl, 'Native WebGL 2 context');
gl.clearColor(1, 0, 0, 1); gl.clear(gl.COLOR_BUFFER_BIT); gl.finish();
const {h264,...interop}=probe.probe(gl._n._replayEGL());
const decoded=spawnSync(ffmpeg,['-hide_banner','-loglevel','error','-f','h264','-i','pipe:0','-frames:v','1','-f','rawvideo','-pix_fmt','rgb24','pipe:1'],{input:h264});
assert.equal(decoded.status,0,decoded.stderr.toString());assert.equal(decoded.stdout.length,256*256*3);
const rgb=[...decoded.stdout.subarray(0,3)];
for(const [i,expected]of [64,127,191].entries())assert(Math.abs(rgb[i]-expected)<=8,`Decoded hardware color ${i}: ${rgb[i]} vs ${expected}`);
console.log(JSON.stringify({ display: getDisplayInfo(), interop, nativeH264Bytes:h264.length, decodedRGB:rgb }, null, 2));
gl.clearColor(0, 1, 0, 1); gl.clear(gl.COLOR_BUFFER_BIT);
const pixel = new Uint8Array(4); gl.readPixels(0, 0, 1, 1, gl.RGBA, gl.UNSIGNED_BYTE, pixel);
assert.deepEqual([...pixel], [0, 255, 0, 255]);
console.log('PASS: native context remains usable after the interop probe.');
