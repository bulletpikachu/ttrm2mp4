import {readFile,writeFile} from 'node:fs/promises';
const commands=JSON.parse(await readFile(new URL('../src/experimental/gl-commands.json',import.meta.url),'utf8'));
const types={u:'GLuint',i:'GLint',f:'GLfloat',b:'GLboolean',z:'GLsizeiptr',o:'const void*'};
const lines=['// Generated by scripts/generate-gl-commands.mjs.',`static constexpr size_t CommandArgs[]={${commands.map(command=>command.types.length).join(',')}};`,
  `static const char*CommandNames[]={${commands.map(command=>JSON.stringify(command.name)).join(',')}};`,
  'struct CommandProfile{int64_t calls=0,samples=0,nanos=0,firstNs=0;};',`static CommandProfile commandProfiles[${commands.length}];`,
  'static const bool profileCommands=getenv("REPLAY_GL_PROFILE_COMMANDS")&&strcmp(getenv("REPLAY_GL_PROFILE_COMMANDS"),"1")==0;',
  'static bool ExecuteCommand(size_t opcode,const double*v,const uint8_t*data,size_t header,size_t end){','switch(opcode){'];
for(const [opcode,command]of commands.entries()){
  const args=[...command.types].map((type,i)=>type==='d'?`(${command.pointer||'const void*'})ptr`:
    type==='o'?`reinterpret_cast<const void*>((uintptr_t)v[${i}])`:`(${types[type]})v[${i}]`);
  lines.push(`case ${opcode}:{`);
  for(const [i,type]of [...command.types].entries())if(type!=='f'){
    const max=type==='u'?4294967295:type==='i'?2147483647:type==='b'?1:9007199254740991;
    const min=type==='i'?-2147483648:0;
    // Explicit doubles avoid MSVC treating -2147483648 as unsigned unary minus.
    lines.push(`if(!std::isfinite(v[${i}])||v[${i}]<${min}.0||v[${i}]>${max}.0)return false;`);
  }
  const pointer=command.types.indexOf('d');
  if(pointer>=0)lines.push(`const double amount=${command.bytes};if(!std::isfinite(amount)||amount<0||amount>67108864)return false;const size_t offset=(size_t)v[${pointer}];if(v[${pointer}]!=offset||offset%8)return false;if(offset&&(offset<header||offset>end||(size_t)amount>end-offset))return false;${command.nullable?'':'if(!offset&&amount)return false;'}const void*ptr=offset?data+offset:nullptr;`);
  const functionName='gl'+command.name[0].toUpperCase()+command.name.slice(1);
  if(command.name==='bindBuffer')lines.push('if(orphanBuffers&&bufferContext&&v[0]==GL_ARRAY_BUFFER)bufferContext->arrayBuffer=(GLuint)v[1];');
  if(command.name==='bufferData')lines.push('if(orphanBuffers&&!shadowOrphan&&bufferContext&&v[0]==GL_ARRAY_BUFFER&&bufferContext->arrayBuffer&&(v[3]==GL_STATIC_DRAW||v[3]==GL_DYNAMIC_DRAW||v[3]==GL_STREAM_DRAW))bufferContext->storage[bufferContext->arrayBuffer]={(GLsizeiptr)v[1],(GLenum)v[3],{}};');
  lines.push(`static auto function=${command.name==='bufferSubData'?'orphanBuffers?&OrphanBufferSubData:':command.name==='bufferData'?'shadowOrphan?&OrphanBufferData:':''}Proc<decltype(&${functionName})>("${functionName}");if(!function)return false;`);
  lines.push(`if(profileCommands){auto&p=commandProfiles[${opcode}];const auto index=p.calls++;if((index&63)==0){const auto t=std::chrono::steady_clock::now();function(${args.join(',')});const auto ns=std::chrono::duration_cast<std::chrono::nanoseconds>(std::chrono::steady_clock::now()-t).count();if(index==0)p.firstNs=ns;else{p.nanos+=ns;p.samples++;}return true;}}function(${args.join(',')});return true;}`);
}
lines.push('default:return false;}}');
await writeFile(new URL('../src/experimental/native/gl-commands.inc',import.meta.url),lines.join('\n')+'\n');

// Fixed-arity writers avoid a shared megamorphic rest-argument/type loop. Both
// implementations emit the same owned, aligned binary format and shadow state.
const updates={
  activeTexture:'state.set(gl.ACTIVE_TEXTURE,[a0]);',
  bindFramebuffer:'if(a0===gl.FRAMEBUFFER||a0===gl.DRAW_FRAMEBUFFER)state.set(gl.DRAW_FRAMEBUFFER_BINDING,[a1]);if(a0===gl.FRAMEBUFFER||a0===gl.READ_FRAMEBUFFER)state.set(gl.READ_FRAMEBUFFER_BINDING,[a1]);',
  useProgram:'state.set(gl.CURRENT_PROGRAM,[a0]);',
  bindVertexArray:'state.set(gl.VERTEX_ARRAY_BINDING,[a0]);',
  viewport:'state.set(gl.VIEWPORT,[a0,a1,a2,a3]);',
  colorMask:'state.set(gl.COLOR_WRITEMASK,[Number(a0),Number(a1),Number(a2),Number(a3)]);',
  bindTexture:'if(a0===gl.TEXTURE_2D)textures.set(state.get(gl.ACTIVE_TEXTURE)[0],a1);',
  enable:'if(enabled.has(a0))enabled.set(a0,true);',
  disable:'if(enabled.has(a0))enabled.set(a0,false);',
};
const writers=['// Generated by scripts/generate-gl-commands.mjs. Do not edit.', 'window.__createGLWriters=(writer,gl,state,textures,enabled,metrics)=>({'];
for(const [opcode,{name,types}]of commands.entries()){
  const args=[...types].map((_,i)=>'a'+i),pointer=types.indexOf('d'),header=(types.length+2)*8;
  writers.push(`${name}:function write_${name}(${args.join(',')}){`);
  if(updates[name])writers.push(`if(state){${updates[name]}}`);
  if(pointer>=0)writers.push(`const data=a${pointer},payload=data==null?null:ArrayBuffer.isView(data)?new Uint8Array(data.buffer,data.byteOffset,data.byteLength):new Uint8Array(data);const size=${header}+(payload?(payload.length+7)&~7:0);`);
  else writers.push(`const size=${header};`);
  writers.push(`const start=writer.allocate(size),at=start/8,w=writer.words;w[at]=${opcode};w[at+1]=start+size;`);
  for(const [i,type]of [...types].entries())writers.push(`w[at+${i+2}]=${i===pointer?`payload?start+${header}:0`:type==='u'?`Number(a${i})>>>0`:`Number(a${i})`};`);
  if(pointer>=0)writers.push(`if(payload)writer.bytes.set(payload,start+${header});`);
  writers.push('metrics.calls++;},');
}
writers.push('});');
await writeFile(new URL('../src/experimental/gl-writers.generated.js',import.meta.url),writers.join('\n')+'\n');
